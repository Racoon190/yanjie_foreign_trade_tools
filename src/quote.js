  /*
   * Pricing model
   * -------------
   * Each line is either:
   *   mode = 'cost'  → price is derived: cost + share of overheads + profit
   *   mode = 'price' → price is a fixed unit price typed by the user
   *
   * Overheads (domestic fees, freight, insurance, other) and the profit rate
   * are spread across the cost-plus lines in proportion to their cost. The
   * last cost line absorbs the rounding residual so that the sum of the line
   * amounts always equals the calculated pool — no more cent drift between the
   * subtotal and unit price × quantity.
   */
  function computeQuote() {
    const rate = currentRate();
    const currency = quoteState.currency;
    const symbol = currencySymbol();
    const items = quoteState.items.map((item) => {
      const qty = Math.max(0, numberOr(item.qty, 0));
      const costCny = Math.max(0, numberOr(item.costCny, 0));
      const mode = item.mode === 'price' ? 'price' : 'cost';
      return {
        ...item,
        qty,
        costCny,
        mode,
        price: Math.max(0, numberOr(item.price, 0)),
        lineCostCny: round2(qty * costCny),
        unitPrice: 0,
        amount: 0,
        belowCost: false,
        marginPct: 0,
      };
    });

    const productCostCny = round2(
      items.reduce((total, item) => total + item.lineCostCny, 0)
    );
    const domestic = Math.max(0, numberOr(quoteState.fees.domestic, 0));
    const totalCostCny = round2(productCostCny + domestic);
    const freight = Math.max(0, numberOr(quoteState.fees.freight, 0));
    const insurance = Math.max(0, numberOr(quoteState.fees.insurance, 0));
    const other = Math.max(0, numberOr(quoteState.fees.other, 0));
    const extraQuote = round2(freight + insurance + other);
    const costInQuote = rate > 0 ? totalCostCny / rate : 0;
    const totalCostQuote = round2(costInQuote + extraQuote);
    const profitRate = Math.max(0, numberOr(quoteState.profitRate, 0));

    const costItems = items.filter((item) => item.mode === 'cost');
    const priceItems = items.filter((item) => item.mode === 'price');

    for (const item of priceItems) {
      item.unitPrice = round2(item.price);
      item.amount = round2(item.unitPrice * item.qty);
    }

    const costPoolCny = round2(
      costItems.reduce((total, item) => total + item.lineCostCny, 0)
    );
    const overheadQuote = rate > 0 ? round2(extraQuote + domestic / rate) : extraQuote;
    const targetPool = round2(
      ((rate > 0 ? costPoolCny / rate : 0) + overheadQuote) * (1 + profitRate / 100)
    );

    const weightTotal =
      costPoolCny > 0
        ? costPoolCny
        : costItems.reduce((total, item) => total + item.qty, 0);
    let allocated = 0;

    for (const [index, item] of costItems.entries()) {
      const weight = costPoolCny > 0 ? item.lineCostCny : item.qty;
      const share = weightTotal > 0 ? (targetPool * weight) / weightTotal : 0;
      let unitPrice;
      if (index === costItems.length - 1) {
        const remaining = Math.max(0, targetPool - allocated);
        unitPrice = item.qty > 0 ? round2(remaining / item.qty) : round2(remaining);
      } else {
        unitPrice = item.qty > 0 ? round2(share / item.qty) : round2(share);
      }
      item.unitPrice = unitPrice;
      item.amount = round2(unitPrice * item.qty);
      allocated = round2(allocated + item.amount);
    }

    const unitCostQuote = rate > 0 ? 1 / rate : 0;
    for (const item of items) {
      const costPerUnit = round2(item.costCny * unitCostQuote);
      item.costPerUnit = costPerUnit;
      item.belowCost = costPerUnit > 0 && item.unitPrice + 1e-9 < costPerUnit;
      item.marginPct =
        item.unitPrice > 0 ? ((item.unitPrice - costPerUnit) / item.unitPrice) * 100 : 0;
    }

    const subtotal = round2(items.reduce((total, item) => total + item.amount, 0));
    const discountRate = clamp(numberOr(quoteState.discountRate, 0), 0, 100);
    const discount = round2((subtotal * discountRate) / 100);
    const total = round2(subtotal - discount);
    const grossProfit = round2(total - totalCostQuote);
    const grossMargin = total > 0 ? (grossProfit / total) * 100 : 0;
    const belowCostCount = items.filter((item) => item.belowCost).length;

    return {
      currency,
      symbol,
      rate,
      items,
      productCostCny,
      domestic,
      totalCostCny,
      extraQuote,
      totalCostQuote,
      profitRate,
      preDiscountTotal: subtotal,
      costPoolCny,
      targetPool,
      fixedSubtotal: round2(priceItems.reduce((total, item) => total + item.amount, 0)),
      subtotal,
      discountRate,
      discount,
      total,
      grossProfit,
      grossMargin,
      belowCostCount,
      hasItems: items.length > 0,
      validUntil: addDaysISO(quoteState.date, quoteState.validityDays),
    };
  }

  function escapeHtml(value) {
    return String(value ?? '').replace(/[&<>"']/g, (character) => {
      const entities = {
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#39;',
      };
      return entities[character];
    });
  }

  function formatNumber(value) {
    const number = numberOr(value, 0);
    return Math.abs(number).toLocaleString('en-US', {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    });
  }

  function formatMoney(value, currency = quoteState.currency) {
    const number = numberOr(value, 0);
    const symbol = CURRENCIES[currency]?.symbol || '$';
    return `${number < 0 ? '-' : ''}${symbol}${formatNumber(Math.abs(number))}`;
  }

