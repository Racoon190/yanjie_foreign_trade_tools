  /* Pull live CNY rates for every supported currency, then refresh the form. */
  async function refreshFxRates({ silent = false } = {}) {
    const els = elementCache;
    if (!window.desktop?.getFxRates) return false;

    if (els.refreshRate) {
      els.refreshRate.disabled = true;
      els.refreshRate.classList.add('is-busy');
    }
    if (els.rateHint) els.rateHint.textContent = '正在获取最新汇率…';

    try {
      const result = await window.desktop.getFxRates();
      if (!result || !result.ok) {
        if (els.rateHint) els.rateHint.textContent = result?.error || '获取失败，请手动填写';
        if (!silent) notify(result?.error || '汇率获取失败，已保留手动填写的数值', { duration: 3600 });
        return false;
      }

      let updated = 0;
      for (const code of Object.keys(CURRENCIES)) {
        const value = Number(result.rates?.[code]);
        if (Number.isFinite(value) && value > 0) {
          quoteState.rates[code] = Math.round(value * 10000) / 10000;
          updated += 1;
        }
      }
      quoteState.ratesUpdatedAt = result.at || Date.now();
      quoteState.ratesSource = result.source || '公开汇率接口';

      if (quoteState.currency !== 'CNY') {
        els.rate.value = quoteState.rates[quoteState.currency];
      }
      updateRateHint();
      scheduleUpdate();
      scheduleSave();

      if (!silent) {
        notify(
          `已更新 ${updated} 种货币汇率（${result.source}）· 1 USD ≈ ${quoteState.rates.USD} CNY`,
          { duration: 4200 }
        );
      }
      return true;
    } catch (error) {
      if (els.rateHint) els.rateHint.textContent = '获取失败，请手动填写';
      if (!silent) notify('汇率获取失败，请检查网络或手动填写', { duration: 3600 });
      return false;
    } finally {
      if (els.refreshRate) {
        els.refreshRate.disabled = quoteState.currency === 'CNY';
        els.refreshRate.classList.remove('is-busy');
      }
    }
  }

