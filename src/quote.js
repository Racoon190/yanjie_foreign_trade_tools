  function validateExport() {
    const errors = [];
    if (!quoteState.seller.company.trim()) errors.push('请填写报价方公司名称');
    if (!quoteState.customer.trim()) errors.push('请填写客户名称');
    if (!quoteState.items.some((item) => item.name.trim() && numberOr(item.qty, 0) > 0)) {
      errors.push('请至少填写一项产品名称和数量');
    }
    if (currentRate() <= 0) errors.push('请填写有效汇率');
    if (!quoteState.date) errors.push('请选择报价日期');
    return errors;
  }

