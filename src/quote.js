  function setExportBusy(busy) {
    const els = elementCache;
    els.exportPdf.disabled = busy;
    els.exportExcel.disabled = busy;
    els.exportPdf.classList.toggle('is-busy', busy);
    els.exportExcel.classList.toggle('is-busy', busy);
    if (busy) {
      els.exportPdf.dataset.original = els.exportPdf.innerHTML;
      els.exportExcel.dataset.original = els.exportExcel.innerHTML;
      const scope = quoteState.exportScope === 'both' ? '中英' : quoteState.exportScope === 'zh' ? '中文' : '英文';
      els.exportPdf.textContent = `正在生成${scope} PDF…`;
      els.exportExcel.textContent = `正在生成${scope} Excel…`;
    } else {
      if (els.exportPdf.dataset.original) {
        els.exportPdf.innerHTML = els.exportPdf.dataset.original;
        delete els.exportPdf.dataset.original;
      }
      if (els.exportExcel.dataset.original) {
        els.exportExcel.innerHTML = els.exportExcel.dataset.original;
        delete els.exportExcel.dataset.original;
      }
    }
  }

  async function exportPdf() {
    const errors = validateExport();
    if (errors.length) {
      notify(errors[0], { error: true, duration: 3800 });
      return;
    }
    setExportBusy(true);
    try {
      const model = computeQuote();
      const documents = exportDocuments('pdf').map((document) => ({
        fileName: document.fileName,
        html: buildPdfHtml(model, document.language),
      }));
      const result = await window.desktop.exportQuotePdf({ documents });
      if (result && result.ok) {
        const scope = quoteState.exportScope === 'both' ? '中英两版' : quoteState.exportScope === 'zh' ? '中文版' : '英文版';
        notify(`已导出${scope} PDF（${result.files.length} 个文件）`, {
          duration: 4600,
        });
        rememberExport(result.files);
      }
    } catch (error) {
      notify(`PDF 导出失败：${error.message || '未知错误'}`, {
        error: true,
        duration: 5000,
      });
    } finally {
      setExportBusy(false);
    }
  }

  async function exportExcel() {
    const errors = validateExport();
    if (errors.length) {
      notify(errors[0], { error: true, duration: 3800 });
      return;
    }
    setExportBusy(true);
    try {
      const model = computeQuote();
      const documents = exportDocuments('xlsx').map((document) => ({
        fileName: document.fileName,
        data: modelToExcel(model, document.language),
      }));
      const result = await window.desktop.exportQuoteExcel({ documents });
      if (result && result.ok) {
        const scope = quoteState.exportScope === 'both' ? '中英两版' : quoteState.exportScope === 'zh' ? '中文版' : '英文版';
        notify(`已导出${scope} Excel（${result.files.length} 个文件）`, {
          duration: 4600,
        });
        rememberExport(result.files);
      }
    } catch (error) {
      notify(`Excel 导出失败：${error.message || '未知错误'}`, {
        error: true,
        duration: 5000,
      });
    } finally {
      setExportBusy(false);
    }
  }

  function rememberExport(files) {
    const first = Array.isArray(files) ? files[0] : null;
    if (!first || !first.path) return;
    const directory = String(first.path).replace(/[\\/][^\\/]+$/, '');
    if (elementCache?.exportNote) {
      elementCache.exportNote.textContent = `已保存到 ${directory}`;
      window.setTimeout(() => updateExportLabels(), 7000);
    }
  }

